/**
 * Flyable interface - Added in for animals that are able to fly.
 * It has more than one abstract method like it says in the assignment spec.
 */
public interface Flyable {

    /**
     * Describes how the animal flies.
     */
    void fly();

    /**
     * Performs a wing health check on the animal.
     */
    void checkWingHealth();

} // end interface Flyable
