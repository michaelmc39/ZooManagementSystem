/**
 * Swimmable interface - added for animals that can swim.
 * Has more than one abstract method like it says in the assignment spec.
 */
public interface Swimmable {

    /**
     * Describes how the animal swims.
     */
    void swim();

    /**
     * Does a fin health check on the animal.
     */
    void checkFinHealth();

} // end interface Swimmable
